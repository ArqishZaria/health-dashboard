class DashboardFilterParsingTests(TestCase):
    def _request_with_get(self, params):
        from django.test import RequestFactory
        rf = RequestFactory()
        return rf.get("/", params)

    def test_parses_date_range(self):
        req = self._request_with_get({"date_from": "2026-01-01", "date_to": "2026-06-30"})
        filters = DashboardFilters(req)
        self.assertEqual(str(filters.date_from), "2026-01-01")
        self.assertEqual(str(filters.date_to), "2026-06-30")

    def test_invalid_date_ignored(self):
        req = self._request_with_get({"date_from": "not-a-date"})
        filters = DashboardFilters(req)
        self.assertIsNone(filters.date_from)

    def test_future_specific_date_is_clamped_to_today(self):
        """A specific-date search can't be in the future - even if someone
        crafts the URL directly (bypassing the date input's max= attribute),
        the backend clamps it to today rather than returning future data."""
        today = timezone.localdate()
        future = today + datetime.timedelta(days=30)
        req = self._request_with_get({
            "year": str(future.year), "month": str(future.month), "day": str(future.day),
        })
        filters = DashboardFilters(req)
        self.assertEqual(filters.date_from, today)
        self.assertEqual(filters.date_to, today)

    def test_future_month_range_is_clamped_to_today(self):
        today = timezone.localdate()
        future_year = today.year + 1
        req = self._request_with_get({"year": str(future_year), "month": "6"})
        filters = DashboardFilters(req)
        self.assertLessEqual(filters.date_to, today)

    def test_querystring_roundtrip(self):
        req = self._request_with_get({"region": "3", "status": "OPEN"})
        filters = DashboardFilters(req)
        qs = filters.querystring()
        self.assertIn("region=3", qs)
        self.assertIn("status=OPEN", qs)

    def test_apply_filters_to_queryset(self):
        region, lc, jk = make_geo()

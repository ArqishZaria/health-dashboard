class MultiSheetUploadTests(TestCase):
    """A workbook with one tab per screening/report type (the common
    Kobo/AKHSP export shape) can be uploaded as a single file: each sheet
    is matched to its Form Type by its tab name and processed
    automatically, instead of only ever reading the first sheet."""

    def setUp(self):
        self.user = User.objects.create_user(username="multisheet", password="pass12345", role=User.Role.NATIONAL)
        self.region, self.lc, self.jk = make_geo()

    def _build_workbook(self, sheets):
        buffer = io.BytesIO()
        with pd.ExcelWriter(buffer, engine="openpyxl") as writer:
            for name, df in sheets.items():
                df.to_excel(writer, sheet_name=name, index=False)
        buffer.seek(0)
        return SimpleUploadedFile(
            "multi.xlsx", buffer.read(),
            content_type="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
        )

    def test_guess_form_type_matches_real_world_sheet_names(self):
        # These are the exact tab names from a real Kobo/AKHSP-style export.
        cases = {
            "Cardiac Risk Assessment": "cardiac_risk_assessment",
            "School H&A Data": "adolescent_health_screening",
            "CBE Screeening": "clinical_breast_examination",
            "Dass Screening": "mental_health_dass21",
            "ICOPE": "elderly_neurological_assessment",
            "eye screening data": "elderly_eye_screening",
            "Camp Screening": "adult_health_screening",
            "Memogram": "mammogram_screening",
            "HBA1C": "hba1c_screening",
        }
        for sheet_name, expected in cases.items():
            self.assertEqual(guess_form_type_from_sheet_name(sheet_name), expected, sheet_name)

    def test_guess_form_type_returns_none_for_unrecognized_name(self):
        self.assertIsNone(guess_form_type_from_sheet_name("Cover Page"))
        self.assertIsNone(guess_form_type_from_sheet_name("Notes"))
        self.assertIsNone(guess_form_type_from_sheet_name(""))


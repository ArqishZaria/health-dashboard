class ImporterUnitTests(TestCase):
    def test_normalize_header(self):
        self.assertEqual(normalize_header("CNIC/NIC Number"), "cnic_nic_number")
        self.assertEqual(normalize_header("  Full Name  "), "full_name")

    def test_map_row_to_canonical(self):
        row = {"full_name": "Ali", "cnic_number": "12345", "unknown_col": "xyz"}
        canonical, leftover = map_row_to_canonical(row)
        self.assertEqual(canonical.get("full_name"), "Ali")
        self.assertEqual(canonical.get("cnic"), "12345")
        self.assertIn("unknown_col", leftover)

    def test_to_bool(self):
        self.assertTrue(to_bool("Yes"))
        self.assertTrue(to_bool("yes"))
        self.assertFalse(to_bool("No"))
        self.assertFalse(to_bool(""))
        self.assertFalse(to_bool(None))

    def test_parse_date_accepts_exact_iso_format(self):
        d = parse_date("2026-01-15")
        self.assertEqual(d, datetime.date(2026, 1, 15))

    def test_parse_date_accepts_excel_midnight_timestamp_variant(self):
        # This is the exact string pandas produces for a genuine Excel date
        # cell once dtype=str forces stringification - must still be accepted.
        d = parse_date("2026-01-15 00:00:00")
        self.assertEqual(d, datetime.date(2026, 1, 15))

    def test_parse_date_rejects_other_formats_with_error(self):
        with self.assertRaises(ImportError_):
            parse_date("15/1/2026")  # DD/MM/YYYY - not the accepted format

    def test_parse_date_rejects_invalid_calendar_date_with_error(self):
        with self.assertRaises(ImportError_):
            parse_date("2026-02-29")  # 2026 is not a leap year

    def test_parse_date_rejects_blank_with_error(self):
        with self.assertRaises(ImportError_):
            parse_date("")
        with self.assertRaises(ImportError_):
            parse_date(None)

    def test_parse_date_never_silently_falls_back_to_today(self):
        # The old behavior silently returned today's date for anything
        # unparseable - confirm that's gone: a bad date now always raises.
        for bad_value in ("not-a-date", "5-March-2026", "2026/13/40"):
            with self.assertRaises(ImportError_):
                parse_date(bad_value)

    def test_infer_risk_category_detects_abnormal_as_high(self):
        leftover = {"diagnosis_findings": "Abnormal - refer to specialist"}
        self.assertEqual(infer_risk_category(leftover), "HIGH")

    def test_infer_risk_category_detects_normal_as_low(self):
        leftover = {"mammography_findings_normal_abnormal": "Normal"}
        self.assertEqual(infer_risk_category(leftover), "LOW")

    def test_infer_risk_category_detects_moderate(self):
        leftover = {"bp_bmi_status": "Moderate risk"}
        self.assertEqual(infer_risk_category(leftover), "MODERATE")

    def test_infer_risk_category_defaults_to_unknown_when_no_hint(self):
        leftover = {"some_unrelated_column": "xyz"}
        self.assertEqual(infer_risk_category(leftover), "UNKNOWN")

    def test_infer_risk_category_high_wins_over_conflicting_columns(self):
        leftover = {"bp_bmi_status": "Normal", "diagnosis_findings": "Abnormal finding"}
        self.assertEqual(infer_risk_category(leftover), "HIGH")

    def test_get_geo_raises_when_region_missing(self):
        with self.assertRaises(ImportError_):
            get_geo("NoSuchRegion", "NoSuchCouncil", "NoSuchJK")

    def test_get_geo_raises_when_local_council_missing_under_existing_region(self):
        region, lc, jk = make_geo()
        with self.assertRaises(ImportError_):
            get_geo(region.name, "NoSuchCouncil", None)

    def test_get_geo_raises_when_jamat_khana_missing_under_existing_local_council(self):
        region, lc, jk = make_geo()
        with self.assertRaises(ImportError_):
            get_geo(region.name, lc.name, "NoSuchJK")

    def test_get_geo_returns_existing_hierarchy_without_creating_anything(self):
        region, lc, jk = make_geo()
        before_regions = Region.objects.count()
        before_lcs = LocalCouncil.objects.count()
        before_jks = JamatKhana.objects.count()

        found_region, found_lc, found_jk = get_geo(region.name, lc.name, jk.name)

        self.assertEqual(found_region, region)
        self.assertEqual(found_lc, lc)
        self.assertEqual(found_jk, jk)
        # Nothing new was created - strictly looked up.
        self.assertEqual(Region.objects.count(), before_regions)
        self.assertEqual(LocalCouncil.objects.count(), before_lcs)
        self.assertEqual(JamatKhana.objects.count(), before_jks)

    def test_get_geo_jamat_khana_optional(self):
        region, lc, jk = make_geo()
        found_region, found_lc, found_jk = get_geo(region.name, lc.name, "")
        self.assertEqual(found_region, region)
        self.assertEqual(found_lc, lc)
        self.assertIsNone(found_jk)

    def test_get_geo_case_insensitive_match(self):
        region, lc, jk = make_geo()
        found_region, found_lc, found_jk = get_geo(region.name.upper(), lc.name.lower(), jk.name.upper())
        self.assertEqual(found_region, region)
        self.assertEqual(found_lc, lc)
        self.assertEqual(found_jk, jk)


